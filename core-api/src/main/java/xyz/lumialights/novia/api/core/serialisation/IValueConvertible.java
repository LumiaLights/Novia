package xyz.lumialights.novia.api.core.serialisation;

import org.jetbrains.annotations.NotNull;



//**********************************************************************************************************************
/**
 * Enables an object to be {@link Value}-convertible, which means, it is allowed to use this object in places where
 * a value may be expected.
 */
public interface IValueConvertible
{
    //******************************************************************************************************************
    /**
     * Gets the currently managed object as a {@link Value} object.
     * @return The {@link Value} object
     */
    @NotNull Value getValue();
    
    /**
     * Sets the internally managed object to the value represented by the passed {@link Value} object.
     * If {@link Value} can't be reasonably converted to the internal representation, this should do nothing.
     * @param value The new {@link Value}
     */
    void setValue(@NotNull Value value);
}
