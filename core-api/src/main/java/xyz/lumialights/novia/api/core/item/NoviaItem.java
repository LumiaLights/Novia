package xyz.lumialights.novia.api.core.item;

import net.minecraft.item.Item;
import net.minecraft.util.Identifier;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;



//**********************************************************************************************************************
/** Provides a base class with useful utilities for custom items. */
public class NoviaItem
    extends Item
{
    //******************************************************************************************************************
    public NoviaItem(@NotNull final Settings settings)
    {
        super(settings);
    }

    //==================================================================================================================
    /**
     * Returns the ItemGroup ID this item should be automatically registered to,
     * or null if it should be registered manually or not at all.
     * @return The ItemGroup ID to register this item with
     */
    public @Nullable Identifier itemGroupId() { return null; }
}
