package xyz.lumialights.novia.api.gui.mixin.client;

import com.mojang.blaze3d.pipeline.RenderPipeline;
import com.mojang.blaze3d.textures.GpuTextureView;
import net.minecraft.client.font.BakedGlyph;
import net.minecraft.client.font.TextRenderLayerSet;
import org.jetbrains.annotations.NotNull;
import org.jetbrains.annotations.Nullable;
import org.spongepowered.asm.mixin.Mixin;
import org.spongepowered.asm.mixin.Shadow;
import org.spongepowered.asm.mixin.gen.Accessor;
import xyz.lumialights.novia.api.gui.impl.BakedGlyphAccessor;



//**********************************************************************************************************************
@Mixin(BakedGlyph.class)
public abstract class BakedGlyphMixin
    implements BakedGlyphAccessor
{
    //******************************************************************************************************************
    @Accessor("textRenderLayers") @Override public abstract @NotNull TextRenderLayerSet textRenderLayers();
    
    @Accessor("minU") @Override public abstract float minU();
    @Accessor("maxU") @Override public abstract float maxU();
    @Accessor("minV") @Override public abstract float minV();
    @Accessor("maxV") @Override public abstract float maxV();
    @Accessor("minX") @Override public abstract float minX();
    @Accessor("maxX") @Override public abstract float maxX();
    @Accessor("minY") @Override public abstract float minY();
    @Accessor("maxY") @Override public abstract float maxY();
    
    @Override
    @Shadow
    public abstract @Nullable GpuTextureView getTexture();
    
    @Override
    @Shadow
    public abstract @NotNull RenderPipeline getPipeline();
}
